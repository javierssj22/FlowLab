import {BOARDS} from '../web/core.mjs';
import {writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
writeFileSync(new URL('boards.json',root),JSON.stringify(BOARDS,null,2)+'\n');
let header='// Generated by scripts/sync-profiles.mjs. Do not edit.\n#pragma once\n';
for(const [i,[key,b]] of Object.entries(BOARDS).entries()) {
  header+=`${i?'#elif':'#if'} CONFIG_IDF_TARGET_${key.toUpperCase()}\nstatic const char* FL_FAMILY="${key}";\nstatic const int FL_GPIO[]={${b.gpio.join(',')}};\nstatic const int FL_ADC[]={${b.adc.join(',')}};\n`;
  header+=`static const int FL_DAC[]={${b.dac.length?b.dac.join(','):'-1'}};\nstatic const int FL_TOUCH[]={${b.touch.length?b.touch.join(','):'-1'}};\n`;
}
header+='#else\n#error "FlowLabBridge: unsupported SoC profile. Add a verified profile first."\n#endif\n';
writeFileSync(new URL('firmware/FlowLabBridge/profiles.h',root),header);
